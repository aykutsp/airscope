#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sorted_and_searchable() {
        // Table must remain sorted for binary search.
        for pair in OUI_TABLE.windows(2) {
            assert!(pair[0].0 < pair[1].0, "OUI_TABLE must be sorted");
        }
        let m: MacAddr = "08:00:27:aa:bb:cc".parse().unwrap();
        assert_eq!(vendor(&m), Some("PCS Computer Systems"));
    }
}
