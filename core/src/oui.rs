//! A tiny built-in OUI -> vendor lookup table.
//!
//! The full IEEE registry is ~35 MB of CSV - way too big to embed.
//! This covers the vendors that show up most often in client lists
//! when hunting on a typical mixed network. It's purely a nicety for
//! the TUI; the returned slice is safe to display next to a MAC.

use crate::MacAddr;

/// Look up the vendor name for the OUI of a MAC address.
/// Returns `None` if unknown.
pub fn vendor(mac: &MacAddr) -> Option<&'static str> {
    let oui = mac.oui();
    OUI_TABLE
        .binary_search_by_key(&oui, |(k, _)| *k)
        .ok()
        .map(|i| OUI_TABLE[i].1)
}

